export function getThumbnail(episode: number, season: number): string {
  return `https://episodes.metahub.space/tt9813792/${season}/${episode}/w780.jpg`;
}

export function getVideoUrl(seasonNumber: number, episodeNumber: number): string {
  const s = String(seasonNumber).padStart(2, "0");
  const e = String(episodeNumber).padStart(2, "0");
  return `/videos/S${s}E${e}.mp4`;
}

